/* =========================================
   CATEGORY FILTERS
========================================= */

const categories = [
  { id: "all", label: "filterAll" },
  { id: "roof", label: "filterRoof" },
  { id: "tiling", label: "filterTiling" },
  { id: "wall", label: "filterWall" },
  { id: "concrete", label: "filterConcrete" },
  { id: "ceiling", label: "filterCeiling" },
  { id: "painting", label: "filterPainting" },
  { id: "cleaning", label: "filterCleaning" }
];

const categoryTranslationKeys = {
  roof: "categoryRoof",
  tiling: "categoryTiling",
  wall: "categoryWall",
  concrete: "categoryConcrete",
  ceiling: "categoryCeiling",
  painting: "categoryPainting",
  cleaning: "categoryCleaning"
};

let currentLanguage = "en";
let activeCategory = "all";


/* =========================================
   RENDER PROJECT FILTER BUTTONS
========================================= */

function renderFilters() {
  const filterContainer = document.getElementById("projectFilters");

  filterContainer.innerHTML = categories.map(category => `
    <button
      class="filter-btn ${activeCategory === category.id ? "active" : ""}"
      data-category="${category.id}">
      ${translations[currentLanguage][category.label]}
    </button>
  `).join("");

  filterContainer.querySelectorAll(".filter-btn").forEach(button => {
    button.addEventListener("click", () => {
      activeCategory = button.dataset.category;
      renderFilters();
      renderProjects();
    });
  });
}


/* =========================================
   RENDER PROJECT CARDS
========================================= */

function renderProjects() {
  const projectGrid = document.getElementById("projectGrid");

  const filteredProjects = activeCategory === "all"
    ? projects
    : projects.filter(project => project.category === activeCategory);

  projectGrid.innerHTML = filteredProjects.map(project => {
    const title = translations[currentLanguage][project.title];
    const description = translations[currentLanguage][project.desc];
    const categoryName = translations[currentLanguage][
      categoryTranslationKeys[project.category]
    ];

    return `
      <article class="project-card">

        <img
          src="${project.image}"
          alt="${title} - ASA Build & Renovation"
          loading="lazy"
          onerror="this.style.display='none'">

        <div class="project-info">

          <span class="project-category">
            ${categoryName}
          </span>

          <h3>${title}</h3>

          <p>${description}</p>

        </div>
      </article>
    `;
  }).join("");

  if (filteredProjects.length === 0) {
    projectGrid.innerHTML = `
      <p class="no-projects">No projects found.</p>
    `;
  }
}


/* =========================================
   CHANGE WEBSITE LANGUAGE
========================================= */

function changeLanguage(language) {
  if (!translations[language]) return;

  currentLanguage = language;

  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;

    if (translations[language][key]) {
      element.textContent = translations[language][key];
    }
  });

  renderFilters();
  renderProjects();

  localStorage.setItem("asaLanguage", language);
}


/* =========================================
   LANGUAGE SELECTOR
========================================= */

const languageSelect = document.getElementById("languageSelect");

languageSelect.addEventListener("change", function () {
  changeLanguage(this.value);
});


/* =========================================
   MOBILE NAVIGATION
========================================= */

const menuToggle = document.getElementById("menuToggle");
const mainNav = document.getElementById("mainNav");

menuToggle.addEventListener("click", () => {
  mainNav.classList.toggle("open");
});

mainNav.querySelectorAll("a").forEach(link => {
  link.addEventListener("click", () => {
    mainNav.classList.remove("open");
  });
});


/* =========================================
   INITIALIZE WEBSITE
========================================= */

const savedLanguage = localStorage.getItem("asaLanguage");

const initialLanguage = translations[savedLanguage]
  ? savedLanguage
  : "en";

languageSelect.value = initialLanguage;

changeLanguage(initialLanguage);
